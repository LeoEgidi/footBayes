# Generates the pages that come from the package sources:
#   - reference/*.qmd from man/*.Rd
#   - news.qmd from NEWS.md
#   - images/readme_*.png from man/figures (the site logo is images/logo.png)
# Run automatically by `quarto render` (pre-render step). The package
# sources are read from the parent folder (the package root), or from
# FOOTBAYES_PKG if set.

pkg <- Sys.getenv("FOOTBAYES_PKG", "..")
stopifnot(file.exists(file.path(pkg, "DESCRIPTION")))

generated <- "<!-- Generated by _prerender.R: do not edit by hand. -->"

write_utf8 <- function(lines, path) {
  dir.create(dirname(path), showWarnings = FALSE, recursive = TRUE)
  writeLines(enc2utf8(lines), path, useBytes = TRUE)
}

read_utf8 <- function(path) readLines(path, encoding = "UTF-8", warn = FALSE)

unescape_html <- function(x) {
  x <- gsub("&lt;", "<", x, fixed = TRUE)
  x <- gsub("&gt;", ">", x, fixed = TRUE)
  x <- gsub("&quot;", "\"", x, fixed = TRUE)
  x <- gsub("&#39;", "'", x, fixed = TRUE)
  gsub("&amp;", "&", x, fixed = TRUE)
}

yaml_string <- function(x) paste0("\"", gsub("\"", "\\\\\"", x), "\"")


