# Rd -> HTML; the code of the Usage and Examples sections becomes
# highlighted R code blocks, \eqn and \deqn become MathJax math.
rd_to_qmd <- function(rd_file) {
  rd <- tools::parse_Rd(rd_file, encoding = "UTF-8")
  html <- paste(utils::capture.output(
    tools::Rd2HTML(rd, out = "", package = "footBayes", dynamic = FALSE,
                   standalone = FALSE, Links = NULL)
  ), collapse = "\n")

  title <- sub("(?s).*?<h2[^>]*>(.*?)</h2>.*", "\\1", html, perl = TRUE)
  title <- unescape_html(gsub("<[^>]+>", "", title))
  html <- sub("(?s).*?</h2>(<span[^>]*></span>)?", "", html, perl = TRUE)

  html <- gsub("(?s)<p style=\"text-align: center;\"><code class=\"reqn\">(.*?)</code>\\s*</p>",
               "<p><span class=\"math display\">\\\\[\\1\\\\]</span></p>", html, perl = TRUE)
  html <- gsub("(?s)<code class=\"reqn\">(.*?)</code>",
               "<span class=\"math inline\">\\\\(\\1\\\\)</span>", html, perl = TRUE)

  sections <- strsplit(html, "<h3>", fixed = TRUE)[[1]][-1]
  body <- unlist(lapply(sections, function(s) {
    heading <- sub("(?s)</h3>.*", "", s, perl = TRUE)
    content <- sub("(?s).*?</h3>", "", s, perl = TRUE)
    if (heading %in% c("Usage", "Examples")) {
      code <- regmatches(content, gregexpr("(?s)<pre><code[^>]*>.*?</code></pre>", content, perl = TRUE))[[1]]
      code <- unescape_html(gsub("(?s)<pre><code[^>]*>|</code></pre>", "", code, perl = TRUE))
      code <- trimws(code, which = "right")
      c(paste("##", heading), "", unlist(lapply(code, function(x) c("```r", x, "```", ""))))
    } else {
      c(paste("##", heading), "", "```{=html}", trimws(content), "```", "")
    }
  }))

  c("---", paste("title:", yaml_string(title)), "---", "", generated, "", body)
}

dir.create("reference", showWarnings = FALSE)
unlink(list.files("reference", pattern = "\\.qmd$", full.names = TRUE))

rd_files <- list.files(file.path(pkg, "man"), pattern = "\\.Rd$", full.names = TRUE)
topics <- tools::file_path_sans_ext(basename(rd_files))
titles <- character()
labels <- character()

# Exported functions and registered S3 methods, used as the labels of the index
ns <- parseNamespaceFile(basename(normalizePath(pkg)), dirname(normalizePath(pkg)))
exported <- c(ns$exports, paste(ns$S3methods[, 1], ns$S3methods[, 2], sep = "."))

for (i in seq_along(rd_files)) {
  qmd <- rd_to_qmd(rd_files[i])
  rd <- tools::parse_Rd(rd_files[i], encoding = "UTF-8")
  tags <- vapply(rd, function(x) attr(x, "Rd_tag"), "")
  aliases <- vapply(rd[tags == "\\alias"], function(x) as.character(x[[1]]), "")
  is_data <- any(vapply(rd[tags == "\\docType"], function(x) as.character(x[[1]]), "") == "data")
  if (!is_data) aliases <- intersect(aliases, exported)
  labels[topics[i]] <- paste0("`", aliases, if (!is_data) "()", "`", collapse = " ")
  titles[topics[i]] <- sub("^title: \"(.*)\"$", "\\1", qmd[2])
  write_utf8(qmd, file.path("reference", paste0(topics[i], ".qmd")))
}

other <- setdiff(topics, unlist(groups))
if (length(other)) groups[["Other"]] <- other

index <- c("---", "title: \"Functions Reference\"", "---", "", generated, "")
for (g in names(groups)) {
  g_topics <- intersect(groups[[g]], topics)
  if (!length(g_topics)) next
  index <- c(index, paste("##", g), "",
             if (!is.na(group_descriptions[g])) c(group_descriptions[[g]], ""),
             "| | |", "|:--|:--|",
             sprintf("| [%s](%s.qmd) | %s |", labels[g_topics], g_topics,
                     gsub("|", "\\|", titles[g_topics], fixed = TRUE)),
             ': {.fb-ref-index tbl-colwidths="[35,65]"}',
             "")
}
write_utf8(index, "reference/index.qmd")


